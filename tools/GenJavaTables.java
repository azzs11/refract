// Generate Unicode tables for the Java flavour from the JDK's own java.lang.Character.
//
//   docker run --rm -v "$PWD/tools:/t:ro" eclipse-temurin:25-jdk-alpine \
//       java /t/GenJavaTables.java > crates/refract-core/src/tables/java.rs
import java.util.*;

public class GenJavaTables {
    interface P { boolean is(int c); }

    static void ranges(StringBuilder out, String name, String doc, P p) {
        out.append("/// ").append(doc).append("\npub static ").append(name).append(": &[(u32, u32)] = &[");
        int start = -1, n = 0;
        for (int c = 0; c <= Character.MAX_CODE_POINT + 1; c++) {
            boolean in = c <= Character.MAX_CODE_POINT && p.is(c);
            if (in && start < 0) start = c;
            if (!in && start >= 0) {
                if (n++ % 6 == 0) out.append("\n    ");
                out.append(String.format("(0x%X, 0x%X), ", start, c - 1));
                start = -1;
            }
        }
        out.append("\n];\n\n");
    }

    static void map(StringBuilder out, String name, String doc, java.util.function.IntUnaryOperator f) {
        out.append("/// ").append(doc).append("\npub static ").append(name).append(": &[(u32, u32)] = &[");
        int n = 0;
        for (int c = 0; c <= Character.MAX_CODE_POINT; c++) {
            int d = f.applyAsInt(c);
            if (d != c) {
                if (n++ % 6 == 0) out.append("\n    ");
                out.append(String.format("(0x%X, 0x%X), ", c, d));
            }
        }
        out.append("\n];\n\n");
    }

    public static void main(String[] args) {
        StringBuilder out = new StringBuilder();
        String v = System.getProperty("java.version");
        out.append("//! GENERATED by tools/GenJavaTables.java — do not edit by hand.\n");
        out.append("//! Source: java.lang.Character of Java ").append(v).append(".\n\n");
        out.append("pub const JAVA_VERSION: &str = \"").append(v).append("\";\n\n");
        map(out, "TO_UPPER", "`Character.toUpperCase(int)` where it changes the code point.", Character::toUpperCase);
        map(out, "TO_LOWER", "`Character.toLowerCase(int)` where it changes the code point.", Character::toLowerCase);
        ranges(out, "NON_SPACING_MARK", "`Character.getType(c) == NON_SPACING_MARK` (for `\\b`).",
               c -> Character.getType(c) == Character.NON_SPACING_MARK);
        ranges(out, "LETTER_OR_DIGIT", "`Character.isLetterOrDigit(c)` (base characters for `\\b`).",
               Character::isLetterOrDigit);
        System.out.print(out);
    }
}
