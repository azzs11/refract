// Generate the JavaScript `\p{..}` tables (u mode) from V8 itself.
//
//     node tools/gen_js_props.mjs > crates/refract-core/src/tables/js_props.rs
//
// Accepted names are found by asking V8 (`new RegExp("\\p{…}", "u")`): general-category values,
// binary properties, and script values for `sc=` / `scx=` (long names from
// tools/data-script-names.txt, short codes by trying every `Xxxx`). Each set is measured with one
// native `matchAll` over a string of every code point.
import { readFileSync } from "node:fs";

const accepts = (body) => {
  try {
    new RegExp(`\\p{${body}}`, "u");
    return true;
  } catch {
    return false;
  }
};

const GC = ("Cased_Letter LC Close_Punctuation Pe Connector_Punctuation Pc Control Cc cntrl " +
  "Currency_Symbol Sc Dash_Punctuation Pd Decimal_Number Nd digit Enclosing_Mark Me " +
  "Final_Punctuation Pf Format Cf Initial_Punctuation Pi Letter L Letter_Number Nl " +
  "Line_Separator Zl Lowercase_Letter Ll Mark M Combining_Mark Math_Symbol Sm Modifier_Letter Lm " +
  "Modifier_Symbol Sk Nonspacing_Mark Mn Number N Open_Punctuation Ps Other C Other_Letter Lo " +
  "Other_Number No Other_Punctuation Po Other_Symbol So Paragraph_Separator Zp Private_Use Co " +
  "Punctuation P punct Separator Z Space_Separator Zs Spacing_Mark Mc Surrogate Cs Symbol S " +
  "Titlecase_Letter Lt Unassigned Cn Uppercase_Letter Lu").split(" ");
const BINARY = ("ASCII ASCII_Hex_Digit AHex Alphabetic Alpha Any Assigned Bidi_Control Bidi_C " +
  "Bidi_Mirrored Bidi_M Case_Ignorable CI Cased Changes_When_Casefolded CWCF " +
  "Changes_When_Casemapped CWCM Changes_When_Lowercased CWL Changes_When_NFKC_Casefolded CWKCF " +
  "Changes_When_Titlecased CWT Changes_When_Uppercased CWU Dash Default_Ignorable_Code_Point DI " +
  "Deprecated Dep Diacritic Dia Emoji Emoji_Component EComp Emoji_Modifier EMod " +
  "Emoji_Modifier_Base EBase Emoji_Presentation EPres Extended_Pictographic ExtPict Extender Ext " +
  "Grapheme_Base Gr_Base Grapheme_Extend Gr_Ext Hex_Digit Hex IDS_Binary_Operator IDSB " +
  "IDS_Trinary_Operator IDST IDS_Unary_Operator IDSU ID_Continue IDC ID_Start IDS " +
  "ID_Compat_Math_Continue ID_Compat_Math_Start Ideographic Ideo Join_Control Join_C " +
  "Logical_Order_Exception LOE Lowercase Lower Math Modifier_Combining_Mark MCM " +
  "Noncharacter_Code_Point NChar Pattern_Syntax Pat_Syn Pattern_White_Space Pat_WS " +
  "Quotation_Mark QMark Radical Regional_Indicator RI Sentence_Terminal STerm Soft_Dotted SD " +
  "Terminal_Punctuation Term Unified_Ideograph UIdeo Uppercase Upper Variation_Selector VS " +
  "White_Space space XID_Continue XIDC XID_Start XIDS").split(" ");

const longScripts = readFileSync(new URL("./data-script-names.txt", import.meta.url), "utf8")
  .split("\n").filter(Boolean);
const scriptCandidates = new Set(longScripts);
const A = "ABCDEFGHIJKLMNOPQRSTUVWXYZ", a = "abcdefghijklmnopqrstuvwxyz";
for (const c1 of A) for (const c2 of a) for (const c3 of a) for (const c4 of a) scriptCandidates.add(c1 + c2 + c3 + c4);

let all = "";
for (let c = 0; c <= 0x10ffff; c++) if (c < 0xd800 || c > 0xdfff) all += String.fromCodePoint(c);

const sets = new Map(); // key -> id
const tables = [];
function measure(body) {
  const ranges = [];
  let start = -1, prev = -2;
  for (const m of all.matchAll(new RegExp(`\\p{${body}}`, "gu"))) {
    const c = m[0].codePointAt(0);
    if (c !== prev + 1) {
      if (start >= 0) ranges.push([start, prev]);
      start = c;
    }
    prev = c;
  }
  if (start >= 0) ranges.push([start, prev]);
  const key = JSON.stringify(ranges);
  if (!sets.has(key)) {
    sets.set(key, tables.length);
    tables.push(ranges);
  }
  return sets.get(key);
}

const lone = [], gc = [], sc = [], scx = [];
for (const v of [...GC, ...BINARY]) if (accepts(v)) lone.push([v, measure(v)]);
for (const v of GC) if (accepts(`General_Category=${v}`)) gc.push([v, measure(`General_Category=${v}`)]);
for (const v of scriptCandidates) {
  if (accepts(`Script=${v}`)) sc.push([v, measure(`Script=${v}`)]);
  if (accepts(`Script_Extensions=${v}`)) scx.push([v, measure(`Script_Extensions=${v}`)]);
}
const byName = (x, y) => (x[0] < y[0] ? -1 : x[0] > y[0] ? 1 : 0);
[lone, gc, sc, scx].forEach((l) => l.sort(byName));

const hex = (n) => "0x" + n.toString(16).toUpperCase();
const out = [
  "//! GENERATED by tools/gen_js_props.mjs — do not edit by hand.",
  `//! Source: V8 ${process.versions.v8} (Node ${process.version}), Unicode ${process.versions.unicode}; \\p{..} in u mode.`,
  "",
];
tables.forEach((rs, i) => {
  out.push(`static S${i}: &[(u32, u32)] = &[${rs.map(([l, h]) => `(${hex(l)}, ${hex(h)})`).join(", ")}];`);
});
const emit = (name, doc, list) => {
  out.push("", `/// ${doc}`, `pub static ${name}: &[(&str, &[(u32, u32)])] = &[`);
  for (const [n, id] of list) out.push(`    (${JSON.stringify(n)}, S${id}),`);
  out.push("];");
};
emit("LONE", "`\\p{Value}`: general-category values and binary properties (exact case).", lone);
emit("GC", "`\\p{General_Category=Value}` / `\\p{gc=Value}`.", gc);
emit("SC", "`\\p{Script=Value}` / `\\p{sc=Value}`.", sc);
emit("SCX", "`\\p{Script_Extensions=Value}` / `\\p{scx=Value}`.", scx);
console.log(out.join("\n"));
