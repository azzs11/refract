// Generate Unicode tables for the JavaScript flavour by querying V8's own RegExp engine.
//
//     node tools/gen_js_tables.mjs > crates/refract-core/src/tables/js.rs
//
// Like tools/gen_python_tables.py, every set is measured on the engine, never derived from the
// Unicode spec, so it carries V8's Unicode version exactly.

const SCALARS = [];
for (let c = 0; c <= 0x10ffff; c++) if (c < 0xd800 || c > 0xdfff) SCALARS.push(c);
const BMP = SCALARS.filter((c) => c <= 0xffff);
const ch = String.fromCodePoint;

function ranges(list, pred) {
  const out = [];
  let start = null, prev = null;
  for (const c of list) {
    if (pred(c)) {
      if (start === null) start = c;
      else if (c !== prev + 1) { out.push([start, prev]); start = c; }
      prev = c;
    } else if (start !== null) { out.push([start, prev]); start = null; }
  }
  if (start !== null) out.push([start, prev]);
  return out;
}

function measured(source, flags, list = SCALARS) {
  const rx = new RegExp(`^(?:${source})$`, flags);
  return ranges(list, (c) => rx.test(ch(c)));
}

// Case-insensitive relation: for each char, the others that /^c$/flags matches. Candidates are
// images and pre-images under toLowerCase/toUpperCase (two hops); each is confirmed by V8.
function foldRelation(flags, list) {
  const near = new Map();
  const link = (a, b) => {
    if (!near.has(a)) near.set(a, new Set());
    near.get(a).add(b);
  };
  for (const c of list) {
    const s = ch(c);
    for (const img of [s.toLowerCase(), s.toUpperCase()]) {
      const cps = [...img];
      if (cps.length === 1) {
        const d = cps[0].codePointAt(0);
        if (d !== c) { link(c, d); link(d, c); }
      }
    }
  }
  const inList = new Set(list);
  const rel = [];
  for (const c of [...near.keys()].sort((a, b) => a - b)) {
    if (!inList.has(c)) continue;
    const cand = new Set(near.get(c));
    for (const n of near.get(c)) for (const m of near.get(n) ?? []) cand.add(m);
    cand.delete(c);
    const escaped = ch(c).replace(/[\\^$.*+?()[\]{}|/]/g, "\\$&");
    const rx = new RegExp(`^${escaped}$`, flags);
    const hits = [...cand].filter((d) => inList.has(d) && rx.test(ch(d))).sort((a, b) => a - b);
    if (hits.length) rel.push([c, hits]);
  }
  return rel;
}

const hex = (n) => "0x" + n.toString(16).toUpperCase();
const out = [];
const emitRanges = (name, rs, doc) => {
  out.push(`/// ${doc}`, `pub static ${name}: &[(u32, u32)] = &[`);
  for (const [lo, hi] of rs) out.push(`    (${hex(lo)}, ${hex(hi)}),`);
  out.push("];", "");
};
const emitRel = (name, rel, doc) => {
  out.push(`/// ${doc}`, `pub static ${name}: &[(u32, &[u32])] = &[`);
  for (const [c, ds] of rel) out.push(`    (${hex(c)}, &[${ds.map(hex).join(", ")}]),`);
  out.push("];", "");
};

out.push("//! GENERATED by tools/gen_js_tables.mjs — do not edit by hand.");
out.push(`//! Source engine: V8 ${process.versions.v8} (Node ${process.version}), Unicode ${process.versions.unicode}.`);
out.push("//! Every set was measured by running the engine on every Unicode scalar value.", "");
out.push(`pub const V8_VERSION: &str = "${process.versions.v8}";`);
out.push(`pub const UNICODE_VERSION: &str = "${process.versions.unicode}";`, "");
emitRanges("SPACE", measured("\\s", "u"), "`\\s` (WhiteSpace ∪ LineTerminator).");
emitRanges("WORD_IU", measured("\\w", "iu"), "`\\w` under the `iu` flags (adds U+017F, U+212A).");
emitRanges("ID_START", ranges(SCALARS, (c) => { try { new RegExp(`(?<${ch(c)}>x)`); return true; } catch { return false; } }),
  "Characters that may start a group name.");
emitRanges("ID_CONTINUE", ranges(SCALARS, (c) => { try { new RegExp(`(?<a${ch(c)}>x)`); return true; } catch { return false; } }),
  "Characters that may continue a group name.");
emitRel("FOLD", foldRelation("i", BMP), "`i` without `u`: per BMP char, the other BMP chars a literal of it matches.");
emitRel("FOLD_U", foldRelation("iu", SCALARS), "`iu`: per char, the other chars a literal of it matches.");
console.log(out.join("\n"));
