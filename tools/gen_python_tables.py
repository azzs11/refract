"""Generate Unicode tables for the Python flavour by querying Python's own `re` engine.

    python3 -I tools/gen_python_tables.py > crates/refract-core/src/tables/python.rs

Every set is measured, not derived from the Unicode spec: `\\w` membership is whatever
`re.fullmatch(r"\\w", c)` says for every scalar value, and the case-insensitive relation is
whatever `re.fullmatch("(?i)" + re.escape(c), d)` says. That captures the engine's Unicode
version and its quirks (e.g. `\\w` uses `str.isalnum()`, and `re._casefix` extra cases).
"""

import platform
import re
import sys
import unicodedata

SCALARS = [c for c in range(0x110000) if not 0xD800 <= c <= 0xDFFF]


def ranges(pred):
    out, start, prev = [], None, None
    for c in SCALARS:
        if pred(c):
            if start is None:
                start = c
            elif c != prev + 1:
                out.append((start, prev))
                start = c
            prev = c
        elif start is not None:
            out.append((start, prev))
            start = None
    if start is not None:
        out.append((start, prev))
    return out


def measured(regex):
    rx = re.compile(regex)
    return ranges(lambda c: rx.fullmatch(chr(c)) is not None)


def fold_relation():
    """For each character c with a non-trivial case-insensitive match set, the other chars d
    such that (?i)c fully matches d. Candidates come from lower/upper/title/casefold images and
    their preimages; every candidate is confirmed by the engine itself."""
    by_lower = {}
    for c in SCALARS:
        ch = chr(c)
        for img in {ch.lower(), ch.upper(), ch.casefold(), ch.title()}:
            if len(img) == 1:
                by_lower.setdefault(img, set()).add(ch)
                by_lower.setdefault(ch, set()).add(img)
    rel = {}
    for ch, near in by_lower.items():
        # two hops of the image/preimage graph covers every known Unicode fold orbit
        cand = set(near)
        for n in list(near):
            cand |= by_lower.get(n, set())
        cand.discard(ch)
        rx = re.compile("(?i)" + re.escape(ch))
        hits = sorted(ord(d) for d in cand if rx.fullmatch(d))
        if hits:
            rel[ord(ch)] = hits
    # Exhaustive confirmation for chars that never appeared as candidates would be 10^12 checks;
    # instead verify the relation is closed: whatever c matches also matches c back.
    for c, ds in rel.items():
        for d in ds:
            if c not in rel.get(d, []):
                print(f"// note: asymmetric fold {c:#x} -> {d:#x}", file=sys.stderr)
    return dict(sorted(rel.items()))


def emit_ranges(name, rs, doc):
    print(f"/// {doc}")
    print(f"pub static {name}: &[(u32, u32)] = &[")
    for lo, hi in rs:
        print(f"    (0x{lo:X}, 0x{hi:X}),")
    print("];\n")


def main():
    print("//! GENERATED by tools/gen_python_tables.py — do not edit by hand.")
    print(f"//! Source engine: CPython {platform.python_version()} `re`, Unicode {unicodedata.unidata_version}.")
    print("//! Every set was measured by running the engine on every Unicode scalar value.\n")
    print(f'pub const PYTHON_VERSION: &str = "{platform.python_version()}";')
    print(f'pub const UNICODE_VERSION: &str = "{unicodedata.unidata_version}";\n')
    emit_ranges("WORD", measured(r"\w"), "`\\w` (str pattern, Unicode mode).")
    emit_ranges("DIGIT", measured(r"\d"), "`\\d` (str pattern, Unicode mode).")
    emit_ranges("SPACE", measured(r"\s"), "`\\s` (str pattern, Unicode mode).")
    emit_ranges("IDENT_START", ranges(lambda c: chr(c).isidentifier()),
                "Characters that may start a group name (`str.isidentifier()`).")
    emit_ranges("IDENT_CONTINUE", ranges(lambda c: ("a" + chr(c)).isidentifier()),
                "Characters that may continue a group name.")
    rel = fold_relation()
    print("/// `(?i)`: for each char, the other chars a case-insensitive literal of it matches.")
    print("pub static FOLD: &[(u32, &[u32])] = &[")
    for c, ds in rel.items():
        print(f"    (0x{c:X}, &[{', '.join(f'0x{d:X}' for d in ds)}]),")
    print("];")


if __name__ == "__main__":
    main()
