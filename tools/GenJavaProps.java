// Generate the Java `\p{..}` tables from the JDK itself.
//
//   docker run --rm -v "$PWD/tools:/t:ro" eclipse-temurin:25-jdk-alpine \
//       java --add-opens java.base/java.lang=ALL-UNNAMED /t/GenJavaProps.java \
//       > crates/refract-core/src/tables/java_props.rs
//
// Name resolution follows CharPredicates (jdk-25-ga). Block and script keys are read from the
// JDK's own alias maps (reflection), so every spelling the JDK accepts is covered. Every set is
// measured by running java.util.regex on every code point, with and without (?i).
import java.lang.reflect.Field;
import java.util.*;
import java.util.regex.Pattern;

public class GenJavaProps {
    static final List<long[]> TABLES = new ArrayList<>();
    static final Map<String, Integer> IDS = new HashMap<>();

    static int intern(List<int[]> ranges) {
        StringBuilder key = new StringBuilder();
        for (int[] r : ranges) key.append(r[0]).append('-').append(r[1]).append(',');
        Integer id = IDS.get(key.toString());
        if (id != null) return id;
        long[] flat = new long[ranges.size() * 2];
        for (int i = 0; i < ranges.size(); i++) { flat[2 * i] = ranges.get(i)[0]; flat[2 * i + 1] = ranges.get(i)[1]; }
        TABLES.add(flat);
        IDS.put(key.toString(), TABLES.size() - 1);
        return TABLES.size() - 1;
    }

    interface P { boolean is(int c); }

    static int measure(P p) {
        List<int[]> out = new ArrayList<>();
        int start = -1;
        for (int c = 0; c <= Character.MAX_CODE_POINT + 1; c++) {
            boolean in = c <= Character.MAX_CODE_POINT && !(c >= 0xD800 && c <= 0xDFFF) && p.is(c);
            if (in && start < 0) start = c;
            if (!in && start >= 0) { out.add(new int[]{start, c - 1}); start = -1; }
        }
        return intern(out);
    }

    static int measureRegex(String regex) {
        Pattern pat = Pattern.compile(regex);
        return measure(c -> pat.matcher(new String(Character.toChars(c))).matches());
    }

    static boolean compiles(String regex) {
        try { Pattern.compile(regex); return true; } catch (Exception e) { return false; }
    }

    @SuppressWarnings("unchecked")
    static Map<String, Object> privateMap(Class<?> cls, String field) throws Exception {
        Field f = cls.getDeclaredField(field);
        f.setAccessible(true);
        return (Map<String, Object>) f.get(null);
    }

    public static void main(String[] args) throws Exception {
        // forProperty: exact-case names (CharPredicates.forProperty, jdk-25-ga).
        String[] props = ("Cn Lu Ll Lt Lm Lo Mn Me Mc Nd Nl No Zs Zl Zp Cc Cf Co Cs Pd Ps Pe Pc Po Sm Sc Sk So Pi Pf " +
            "L M N Z C P S LC LD L1 all ASCII Alnum Alpha Blank Cntrl Digit Graph Lower Print Punct Space Upper XDigit " +
            "javaLowerCase javaUpperCase javaAlphabetic javaIdeographic javaTitleCase javaDigit javaDefined javaLetter " +
            "javaLetterOrDigit javaJavaIdentifierStart javaJavaIdentifierPart javaUnicodeIdentifierStart " +
            "javaUnicodeIdentifierPart javaIdentifierIgnorable javaSpaceChar javaWhitespace javaISOControl javaMirrored").split(" ");
        // forUnicodeProperty / getPosixPredicate: upper-case keys.
        String[] uprops = ("ALPHABETIC ASSIGNED CONTROL EMOJI EMOJI_PRESENTATION EMOJI_MODIFIER EMOJI_MODIFIER_BASE " +
            "EMOJI_COMPONENT EXTENDED_PICTOGRAPHIC HEXDIGIT HEX_DIGIT IDEOGRAPHIC JOINCONTROL JOIN_CONTROL LETTER LOWERCASE " +
            "NONCHARACTERCODEPOINT NONCHARACTER_CODE_POINT TITLECASE PUNCTUATION UPPERCASE WHITESPACE WHITE_SPACE WORD " +
            "ALPHA LOWER UPPER SPACE PUNCT XDIGIT ALNUM CNTRL DIGIT BLANK GRAPH PRINT").split(" ");

        StringBuilder out = new StringBuilder();
        out.append("//! GENERATED by tools/GenJavaProps.java — do not edit by hand.\n");
        out.append("//! Source: java.util.regex of Java ").append(System.getProperty("java.version")).append(".\n\n");

        StringBuilder lists = new StringBuilder();
        lists.append("/// `forProperty` (exact case): (name, set, set under (?i)).\n");
        lists.append("pub static PROPERTY: &[(&str, usize, usize)] = &[\n");
        for (String n : props) {
            if (!compiles("\\p{" + n + "}")) continue;
            lists.append(String.format("    (\"%s\", %d, %d),\n", n, measureRegex("\\p{" + n + "}"), measureRegex("(?i)\\p{" + n + "}")));
        }
        lists.append("];\n\n/// `forUnicodeProperty` (upper-case keys, reached through `Is`).\n");
        lists.append("pub static UNICODE_PROPERTY: &[(&str, usize, usize)] = &[\n");
        for (String n : uprops) {
            if (!compiles("\\p{Is" + n + "}")) continue;
            lists.append(String.format("    (\"%s\", %d, %d),\n", n, measureRegex("\\p{Is" + n + "}"), measureRegex("(?i)\\p{Is" + n + "}")));
        }
        // Scripts: enum names and the JDK's alias map (upper-case keys).
        Map<Character.UnicodeScript, Integer> scriptSet = new HashMap<>();
        for (Character.UnicodeScript s : Character.UnicodeScript.values()) {
            final Character.UnicodeScript sc = s;
            scriptSet.put(s, measure(c -> Character.UnicodeScript.of(c) == sc));
        }
        TreeMap<String, Integer> scriptKeys = new TreeMap<>();
        for (Character.UnicodeScript s : Character.UnicodeScript.values()) scriptKeys.put(s.name(), scriptSet.get(s));
        for (Map.Entry<String, Object> e : privateMap(Character.UnicodeScript.class, "aliases").entrySet()) {
            scriptKeys.put(e.getKey().toUpperCase(Locale.ENGLISH), scriptSet.get((Character.UnicodeScript) e.getValue()));
        }
        lists.append("];\n\n/// `UnicodeScript.forName` keys (upper case).\npub static SCRIPT: &[(&str, usize)] = &[\n");
        for (Map.Entry<String, Integer> e : scriptKeys.entrySet()) lists.append(String.format("    (\"%s\", %d),\n", e.getKey(), e.getValue()));
        // Blocks: the JDK's name map (canonical, no-space and identifier spellings, upper case).
        Map<String, Object> blocks = privateMap(Character.UnicodeBlock.class, "map");
        Map<Object, Integer> blockSet = new HashMap<>();
        TreeMap<String, Integer> blockKeys = new TreeMap<>();
        for (Map.Entry<String, Object> e : blocks.entrySet()) {
            final Character.UnicodeBlock b = (Character.UnicodeBlock) e.getValue();
            Integer id = blockSet.computeIfAbsent(b, k -> measure(c -> Character.UnicodeBlock.of(c) == b));
            blockKeys.put(e.getKey().toUpperCase(Locale.US), id);
        }
        lists.append("];\n\n/// `UnicodeBlock.forName` keys (upper case).\npub static BLOCK: &[(&str, usize)] = &[\n");
        for (Map.Entry<String, Integer> e : blockKeys.entrySet()) lists.append(String.format("    (\"%s\", %d),\n", e.getKey(), e.getValue()));
        lists.append("];\n");

        out.append("/// Distinct sets, as inclusive ranges.\npub static SETS: &[&[(u32, u32)]] = &[\n");
        for (long[] t : TABLES) {
            out.append("    &[");
            for (int i = 0; i < t.length; i += 2) out.append(String.format("(0x%X, 0x%X), ", t[i], t[i + 1]));
            out.append("],\n");
        }
        out.append("];\n\n").append(lists);
        System.out.print(out);
    }
}
