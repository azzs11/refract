// Generate Unicode tables for the Go flavour from Go's own unicode package, mirroring
// regexp/syntax's unicodeTable() name resolution exactly.
//
//	docker run --rm -v "$PWD/tools:/t" golang:1.27-alpine go run /t/gen_go_tables.go \
//	    > crates/refract-core/src/tables/go.rs
package main

import (
	"fmt"
	"runtime"
	"sort"
	"strings"
	"unicode"
)

// canonicalName is copied from regexp/syntax (Go 1.27).
func canonicalName(name string) string {
	var b []byte
	first := true
	for i := range len(name) {
		c := name[i]
		switch {
		case c == '_' || c == '-' || c == ' ':
			c = ' '
		case first:
			if 'a' <= c && c <= 'z' {
				c -= 'a' - 'A'
			}
			first = false
		default:
			if 'A' <= c && c <= 'Z' {
				c += 'a' - 'A'
			}
		}
		if b == nil {
			if c == name[i] && c != ' ' {
				continue
			}
			b = make([]byte, i, len(name))
			copy(b, name[:i])
		}
		if c == ' ' {
			continue
		}
		b = append(b, c)
	}
	if b == nil {
		return name
	}
	return string(b)
}

type rng struct{ lo, hi rune }

func ranges(t *unicode.RangeTable) []rng {
	var out []rng
	if t == nil {
		return out
	}
	for _, r := range t.R16 {
		for c := rune(r.Lo); c <= rune(r.Hi); c += rune(r.Stride) {
			out = append(out, rng{c, c})
		}
	}
	for _, r := range t.R32 {
		for c := rune(r.Lo); c <= rune(r.Hi); c += rune(r.Stride) {
			out = append(out, rng{c, c})
		}
	}
	sort.Slice(out, func(i, j int) bool { return out[i].lo < out[j].lo })
	var merged []rng
	for _, r := range out {
		if n := len(merged); n > 0 && r.lo <= merged[n-1].hi+1 {
			if r.hi > merged[n-1].hi {
				merged[n-1].hi = r.hi
			}
			continue
		}
		merged = append(merged, r)
	}
	return merged
}

type entry struct {
	name       string // canonical lookup name
	tab, fold  string // table identifiers ("" = none)
	negated    bool
}

func main() {
	tables := map[string][]rng{}
	add := func(id string, t *unicode.RangeTable) string {
		if t == nil {
			return ""
		}
		if _, ok := tables[id]; !ok {
			tables[id] = ranges(t)
		}
		return id
	}
	var entries []entry
	seen := map[string]bool{}
	push := func(e entry) {
		if !seen[e.name] {
			seen[e.name] = true
			entries = append(entries, e)
		}
	}
	any := &unicode.RangeTable{R32: []unicode.Range32{{Lo: 0, Hi: unicode.MaxRune, Stride: 1}}}
	ascii := &unicode.RangeTable{R16: []unicode.Range16{{Lo: 0, Hi: 0x7F, Stride: 1}}}
	asciiFold := &unicode.RangeTable{R16: []unicode.Range16{{Lo: 0, Hi: 0x7F, Stride: 1}, {Lo: 0x17F, Hi: 0x17F, Stride: 1}, {Lo: 0x212A, Hi: 0x212A, Stride: 1}}}
	// Order follows unicodeTable(): special cases, Categories, Scripts, aliases.
	push(entry{"Any", add("ANY", any), add("ANY", any), false})
	push(entry{"Assigned", add("C_Cn", unicode.Cn), add("C_Cn", unicode.Cn), true})
	push(entry{"Ascii", add("ASCII", ascii), add("ASCII_FOLD", asciiFold), false})
	push(entry{"Lc", add("C_LC", unicode.Categories["LC"]), add("F_C_LC", unicode.FoldCategory["LC"]), false})
	var cats, scripts, aliasNames []string
	for k := range unicode.Categories {
		cats = append(cats, k)
	}
	for k := range unicode.Scripts {
		scripts = append(scripts, k)
	}
	for k := range unicode.CategoryAliases {
		aliasNames = append(aliasNames, k)
	}
	sort.Strings(cats)
	sort.Strings(scripts)
	sort.Strings(aliasNames)
	for _, k := range cats {
		// unicodeTable looks up Categories[canonical], so only canonical keys are reachable.
		if canonicalName(k) == k {
			push(entry{k, add("C_"+k, unicode.Categories[k]), add("F_C_"+k, unicode.FoldCategory[k]), false})
		}
	}
	for _, k := range scripts {
		if canonicalName(k) == k {
			push(entry{k, add("S_"+k, unicode.Scripts[k]), add("F_S_"+k, unicode.FoldScript[k]), false})
		}
	}
	for _, a := range aliasNames {
		actual := unicode.CategoryAliases[a]
		push(entry{canonicalName(a), add("C_"+actual, unicode.Categories[actual]), add("F_C_"+actual, unicode.FoldCategory[actual]), false})
	}
	for _, k := range scripts {
		push(entry{canonicalName(k), add("S_"+k, unicode.Scripts[k]), add("F_S_"+k, unicode.FoldScript[k]), false})
	}

	ident := func(id string) string { return "T_" + strings.ToUpper(strings.ReplaceAll(id, "-", "_")) }
	fmt.Println("//! GENERATED by tools/gen_go_tables.go — do not edit by hand.")
	fmt.Printf("//! Source: Go %s unicode package (Unicode %s), name resolution of regexp/syntax.\n\n", runtime.Version(), unicode.Version)
	fmt.Printf("pub const GO_VERSION: &str = %q;\n", runtime.Version())
	fmt.Printf("pub const UNICODE_VERSION: &str = %q;\n\n", unicode.Version)
	var ids []string
	for id := range tables {
		ids = append(ids, id)
	}
	sort.Strings(ids)
	for _, id := range ids {
		fmt.Printf("static %s: &[(u32, u32)] = &[", ident(id))
		for i, r := range tables[id] {
			if i%6 == 0 {
				fmt.Print("\n    ")
			}
			fmt.Printf("(0x%X, 0x%X), ", r.lo, r.hi)
		}
		fmt.Println("\n];")
	}
	fmt.Println("\n/// `\\p{name}` lookup: (canonical name, table, fold table, negated), in resolution order.")
	fmt.Println("pub static PROPERTIES: &[(&str, &[(u32, u32)], &[(u32, u32)], bool)] = &[")
	for _, e := range entries {
		fold := "&[]"
		if e.fold != "" {
			fold = ident(e.fold)
		}
		fmt.Printf("    (%q, %s, %s, %v),\n", e.name, ident(e.tab), fold, e.negated)
	}
	fmt.Println("];")
	// Simple case folding orbits, as used by (?i) on literals and classes.
	fmt.Println("\n/// `(?i)`: per rune, the other members of its unicode.SimpleFold orbit.")
	fmt.Println("pub static FOLD: &[(u32, &[u32])] = &[")
	for r := rune(0); r <= unicode.MaxRune; r++ {
		f := unicode.SimpleFold(r)
		if f == r {
			continue
		}
		var orbit []string
		for x := f; x != r; x = unicode.SimpleFold(x) {
			orbit = append(orbit, fmt.Sprintf("0x%X", x))
		}
		sort.Strings(orbit)
		fmt.Printf("    (0x%X, &[%s]),\n", r, strings.Join(orbit, ", "))
	}
	fmt.Println("];")
}
