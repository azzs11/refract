"""Summarise `results.jsonl` (from `refract batch`) into bench/results/census.{json,md}.

    python3 bench/census/analyze.py
"""

from __future__ import annotations

import json
from collections import Counter, defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
RESULTS = HERE.parent / "results"
FLAVORS = ["js", "python", "go", "java", "rust"]
LINE_TERMS = set("\n\r  \x85")


def category(witness: str) -> str:
    if any(c in LINE_TERMS for c in witness):
        return "line terminators (`$`, `.`, `^` in multiline)"
    if any(ord(c) > 127 for c in witness):
        return "non-ASCII characters (Unicode classes, case folding)"
    return "ASCII-only witness (syntax read differently)"


def pct(a: int, b: int) -> str:
    return f"{100 * a / b:.1f}%" if b else "–"


def main() -> int:
    rows = [json.loads(line) for line in (HERE / "results.jsonl").open()]
    corpus = {r["id"]: r for r in map(json.loads, (HERE / "corpus.jsonl").open())}
    per_src: dict[str, Counter[str]] = defaultdict(Counter)
    pair: dict[tuple[str, str], Counter[str]] = defaultdict(Counter)
    cats: Counter[str] = Counter()
    reject_reasons: Counter[str] = Counter()
    replay: Counter[str] = Counter()
    contradictions = []
    examples: dict[str, list[dict[str, str]]] = defaultdict(list)
    for r in rows:
        src = r["source"]
        per_src[src]["patterns"] += 1
        if "error" in r:
            kind = r["error"]["kind"]
            per_src[src][f"source {kind}"] += 1
            rp = r["error"].get("replay", "-")
            if kind == "syntax":
                replay[f"source rejection {rp.split(' ')[0].split(':')[0]}"] += 1
                if rp.startswith("CONTRADICTED"):
                    contradictions.append({"pattern": r["pattern"], "flavor": src, "what": "our parser rejects it, the engine accepts it"})
            continue
        per_src[src]["analysed"] += 1
        verdicts = []
        for e in r["engines"]:
            v = e["verdict"].split(" ")[0]
            if v == "SAME" and e["verdict"] != "SAME":
                v = "SAME-bounded"
            verdicts.append(v)
            pair[(src, e["flavor"])][v] += 1
            status = e["status"]
            if v in ("DIFFERS", "REJECTS"):
                key = "confirmed" if status == "confirmed" else "contradicted" if status.startswith("CONTRADICTED") else "predicted"
                replay[f"{v.lower()} {key}"] += 1
                if key == "contradicted":
                    contradictions.append({"pattern": r["pattern"], "flavor": src, "target": e["flavor"], "what": status,
                                           "witness": (e.get("witness") or {}).get("escaped", "")})
            if v == "REJECTS":
                reject_reasons[f"{e['flavor']}: {e['note'][:70]}"] += 1
            if v == "DIFFERS" and e.get("witness"):
                c = category(e["witness"]["text"])
                cats[c] += 1
                if len(examples[c]) < 4 and len(r["pattern"]) <= 40 and all(x["pattern"] != r["pattern"] for x in examples[c]):
                    examples[c].append({"pattern": r["pattern"], "from": src, "to": e["flavor"], "witness": e["witness"]["escaped"],
                                        "source_matches": "matches" if e["source_matches"] else "no match"})
        if all(v.startswith("SAME") for v in verdicts):
            per_src[src]["same everywhere"] += 1
        if any(v in ("DIFFERS", "REJECTS") for v in verdicts):
            per_src[src]["disagrees somewhere"] += 1
        if any(v == "DIFFERS" for v in verdicts):
            per_src[src]["differs somewhere"] += 1
        if any(v == "REJECTS" for v in verdicts):
            per_src[src]["rejected somewhere"] += 1
        if any(v == "NOT" for v in verdicts):
            per_src[src]["not analysed somewhere"] += 1
    total = Counter()
    for c in per_src.values():
        total.update(c)
    out = {
        "patterns": len(rows),
        "corpus_sources": sorted({c["ecosystem"] for c in corpus.values()}),
        "per_source": {k: dict(v) for k, v in per_src.items()},
        "total": dict(total),
        "pairs": {f"{a}->{b}": dict(v) for (a, b), v in sorted(pair.items())},
        "difference_categories": dict(cats),
        "rejection_reasons": dict(reject_reasons.most_common()),
        "replay": dict(replay),
        "contradictions": contradictions,
        "examples": examples,
    }
    (RESULTS / "census.json").write_text(json.dumps(out, indent=1, ensure_ascii=False) + "\n")

    md = ["# Census: real-world regexes across five engines (P8)", "",
          "Generated by `bench/census/analyze.py` from `refract batch` over the corpus of",
          "`bench/census/collect.py` (manifest: `bench/census/manifest.json`). Each pattern is taken",
          "from library code in its own language and compared, under the operation its call performs",
          "(search unless `fullmatch`/`matches`), with what someone porting it would write in each",
          "other engine. Every DIFFERS witness and every rejection is replayed on the real engines.", "",
          "## Per source language", "",
          "A **disagreement** is either a difference (the engines match different strings; the",
          "shortest witness is shown) or a rejection (the engine refuses the pattern, so the engines",
          "disagree on every input, the empty string included).", "",
          "| written for | patterns | analysed | same in all 4 others | **disagrees somewhere** | of which: differs | of which: rejected | not analysed somewhere |",
          "|---|---|---|---|---|---|---|---|"]
    for f in FLAVORS + ["total"]:
        c = total if f == "total" else per_src.get(f)
        if not c:
            continue
        a = c["analysed"]
        md.append(f"| {f} | {c['patterns']} | {a} | {c['same everywhere']} ({pct(c['same everywhere'], a)}) | "
                  f"**{c['disagrees somewhere']} ({pct(c['disagrees somewhere'], a)})** | "
                  f"{c['differs somewhere']} ({pct(c['differs somewhere'], a)}) | {c['rejected somewhere']} ({pct(c['rejected somewhere'], a)}) | "
                  f"{c['not analysed somewhere']} ({pct(c['not analysed somewhere'], a)}) |")
    md += ["", "## Source → target", "", "| from → to | same (proven) | same (bounded) | disagrees | differs | rejects | not analysed |", "|---|---|---|---|---|---|---|"]
    for (a, b), v in sorted(pair.items(), key=lambda kv: (FLAVORS.index(kv[0][0]), FLAVORS.index(kv[0][1]))):
        n = sum(v.values())
        md.append(f"| {a} → {b} | {pct(v['SAME'], n)} | {pct(v['SAME-bounded'], n)} | {pct(v['DIFFERS'] + v['REJECTS'], n)} | {pct(v['DIFFERS'], n)} | {pct(v['REJECTS'], n)} | {pct(v['NOT'], n)} |")
    md += ["", "## What the differences are about (by shortest witness)", "", "| category | differing pairs |", "|---|---|"]
    for c, n in cats.most_common():
        md.append(f"| {c} | {n} ({pct(n, sum(cats.values()))}) |")
    md += ["", "Examples (short patterns):", ""]
    for c, ex in examples.items():
        md.append(f"- *{c}*: " + "; ".join(f"`{e['pattern']}` ({e['from']} → {e['to']}) on {e['witness']}: {e['from']} {e['source_matches']}" for e in ex))
    md += ["", "Most common reasons a target engine rejects a pattern:", "", "| target: error | count |", "|---|---|"]
    for k, n in reject_reasons.most_common(10):
        md.append(f"| {k.replace('|', '\\|')} | {n} |")
    md += ["", "## Do the predictions hold on the real engines? (RQ2)", "", "| outcome | count |", "|---|---|"]
    for k, n in sorted(replay.items()):
        md.append(f"| {k} | {n} |")
    md += ["", f"All {replay['differs confirmed'] + replay['rejects confirmed']:,} disagreements found were replayed: {replay['differs confirmed']:,} differences (shortest witness run on both engines) and {replay['rejects confirmed']:,} rejections (the engine's own compile error)."]
    md += ["", f"Contradictions (model ≠ engine): **{len(contradictions)}**" + (" — listed in `census.json`." if contradictions else "."), "",
           "## Context", "",
           "Davis et al. (\"Why aren't regular expressions a lingua franca?\", ESEC/FSE 2019) found about",
           "15% of their polyglot corpus behaved differently across eight languages, by differential",
           "testing on generated inputs. This census differs in corpus (2026 library code, five",
           "engines), method (exact equivalence with shortest witnesses, replayed on the engines) and",
           "porting assumption (the same pattern text, JS literals reduced to their source), so the",
           "numbers are not directly comparable; they answer the same question for today's engines."]
    (RESULTS / "census.md").write_text("\n".join(md) + "\n")
    print("\n".join(md[9:9 + len(FLAVORS) + 2]))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
